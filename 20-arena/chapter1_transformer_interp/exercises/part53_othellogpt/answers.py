  layer: int = 6
  pos_start: int = 5
  pos_end: int = -5  # i.e. we slice [pos_start: model.n_ctx + pos_end]

  # Game state (options are blank/mine/theirs)
  options: int = 3
  rows: int = 8
  cols: int = 8

