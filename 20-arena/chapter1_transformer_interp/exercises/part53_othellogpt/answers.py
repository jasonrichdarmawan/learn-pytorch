"""
# What is a probe

From the MI Dynalist notes:
> Probing is a technique for identifying directions
> in network activation space that correspond 
> to a concept/feature
>
> In spirit, you give the network a bunch of inputs
> with that feature, and a bunch without it. 
> You train a linear map on a specific activation (
> eg the output of layer 5) which distinguishes these
> two sets, giving a 1D linear map (a probe),
> corresponding to a direction in activation space,
> which likely corresponds to that feature

Probes can be a very valuable tool to help us
better understand the concepts represented in our model.
However, there are two big caveats to keep in mind:
1. Probes give us a direction, but they don't give
   us a causal story about how that direction
   got into the model in the first place, or how
   the model is using that direction
2. Probes (especially nonlinear probes) can be
   hiding a lot of computation under their surface.

In the original paper analysing Othello, the
authors used nonlinear probing to find important
directions. This went against a fundamental
intuition - that models fundamentally store things
in linear ways, and so we should be able to access
them with linear probes. In these exercises, we'll
be using linear probes.
"""

